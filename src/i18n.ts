// Tiny localisation layer. English strings are the keys; a missing translation falls back
// to the key, so new UI text never breaks the German build.

export type LangSetting = "system" | "en" | "de";
export type Lang = "en" | "de";

export let lang: Lang = "en";

export function initLanguage(setting: LangSetting): Lang {
  if (setting === "en" || setting === "de") lang = setting;
  else lang = /^de\b/i.test(navigator.language) ? "de" : "en";
  document.documentElement.lang = lang;
  return lang;
}

/** Translate `key`, substituting `{name}` placeholders from `vars`. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = lang === "de" ? (de[key] ?? key) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  return s;
}

